-- V022: Multi-agent coordination
-- Adds:
--   1. AppAgentSharedContext — DB-backed blackboard scoped by WorkflowId (GUID).
--      Survives server restarts; works across different users/roles in the same workflow.
--   2. platform-multi-agent library — three BuiltIn tools:
--        call_agent            : invoke another agent by SkillKey, propagates WorkflowId
--        write_shared_context  : UPSERT a JSON value into the shared blackboard
--        read_shared_context   : SELECT a JSON value from the shared blackboard

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Shared context blackboard table
-- ─────────────────────────────────────────────────────────────────────────────

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'AppAgentSharedContext')
CREATE TABLE dbo.AppAgentSharedContext (
    ScopeId    NVARCHAR(200) NOT NULL,   -- WorkflowId GUID (generated by orchestrator agent)
    ContextKey NVARCHAR(200) NOT NULL,
    DataJson   NVARCHAR(MAX) NOT NULL,
    UpdatedAt  DATETIME2     NOT NULL DEFAULT GETUTCDATE(),
    CONSTRAINT PK_AppAgentSharedContext PRIMARY KEY (ScopeId, ContextKey)
);
GO

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. platform-multi-agent library
-- ─────────────────────────────────────────────────────────────────────────────

IF NOT EXISTS (SELECT 1 FROM dbo.AppAgentToolLibrary WHERE LibraryKey = 'platform-multi-agent')
INSERT INTO dbo.AppAgentToolLibrary (LibraryKey, DomainKey, LibraryName, Description, ToolCategory, IsActive)
VALUES (
    'platform-multi-agent',
    'platform',
    'Multi-Agent Coordination',
    'Tools that let agents call other agents and share structured data across a workflow. Subscribe the orchestrator agent and all worker agents to this library to enable coordination. Worker agents must have ExecutionMode=Deterministic.',
    'BuiltIn',
    1
);
GO

